-- ============================================================================
-- Table 1: users (MANDATORY)
-- Represents registered users with hashed passwords and assigned roles.
-- ============================================================================
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    hashed_password TEXT NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'user',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Case-insensitive unique index on email to prevent duplicates like Test@a.com and test@a.com
CREATE UNIQUE INDEX IF NOT EXISTS ix_users_email_lower ON users (LOWER(email));


-- ============================================================================
-- Table 2: tasks (MANDATORY)
-- Represents user-owned tasks with strict status, priority and owner constraints.
-- ============================================================================
CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    priority VARCHAR(10) NOT NULL DEFAULT 'medium',
    due_date DATE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    
    -- Business Rules & Integrity Constraints
    CONSTRAINT task_status_allowed CHECK (status IN ('pending', 'in_progress', 'completed')),
    CONSTRAINT task_priority_allowed CHECK (priority IN ('low', 'medium', 'high')),
    CONSTRAINT task_title_not_blank CHECK (LENGTH(BTRIM(title)) > 0)
);

-- Performance Indexes for fast lookups by owner and status filtering
CREATE INDEX IF NOT EXISTS ix_tasks_user_id ON tasks(user_id);
CREATE INDEX IF NOT EXISTS ix_tasks_user_status ON tasks(user_id, status);


-- ============================================================================
-- Table 3: projects (TASKFLOW EXTENSION - PHASE 2)
-- Optional extension table allowing users to group related tasks.
-- A task can optionally link to a project (project_id NULLABLE).
-- ============================================================================
CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(160) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    start_date DATE,
    due_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    
    CONSTRAINT project_status_allowed CHECK (status IN ('active', 'completed', 'archived')),
    CONSTRAINT project_name_not_blank CHECK (LENGTH(BTRIM(name)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_projects_owner ON projects(owner_user_id);

-- Add optional project_id relationship to tasks
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name = 'tasks' AND column_name = 'project_id'
    ) THEN
        ALTER TABLE tasks ADD COLUMN project_id BIGINT NULL REFERENCES projects(id) ON DELETE SET NULL;
        CREATE INDEX ix_tasks_project_id ON tasks(project_id);
    END IF;
END $$;
